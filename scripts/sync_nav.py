#!/usr/bin/env python3
"""Generate the site menu (nav) of each adopting page from one source.

Orisod 2.0 keeps the nav in one place and copies it into each page, so pages stay
self-contained. A page that carries the generated menu has three marked regions:

  - in its inline <style>:   /* site-nav.css: start. ... */ ... /* site-nav.css: end */
    a copy of assets/nav/site-nav.css
  - in its <body>:           <!-- site-nav: start. ... --> ... <!-- site-nav: end -->
    the <header class="site-nav"> built from assets/nav/site-nav.html and
    assets/nav/strings.json, with the category flyouts listed from the /tools cards,
    plus the one-line script that keeps --site-nav-h in step
  - near the end of <body>:  <!-- site-nav.js: start. ... --> ... <!-- site-nav.js: end -->
    a <script> holding a copy of assets/nav/site-nav.js

    python scripts/sync_nav.py                 # dry run (default): list the pages whose regions are out of date
    python scripts/sync_nav.py --write         # rewrite every out-of-date region
    python scripts/sync_nav.py --check         # exit 1 if any region differs or a page's regions are broken
    python scripts/sync_nav.py --add PAGE...   # adopt pages: turn their hand-copied nav into the three regions

Only the text between the markers is ever rewritten; everything else on a page stays
byte for byte as it is, and a page without the markers is never touched (unless named
with --add). Line endings are compared loosely (CRLF and LF are the same), and the
regions are written with the page's own line endings.

What the script works out per page:
  - language: a page under es/ is Spanish (strings, /es/ links, /es/tools/ cards)
  - the language switch: the same page in the other language (/x/ <-> /es/x/)
  - the current item: aria-current="page" on "All Tools" on /tools and on "Blog" on
    the blog index (PAGE_SETTINGS), nowhere else
  - the search icon: on the homepages and /tools it brings the page's own search box
    into view (data-search-target, plus data-search-watch on the homepages, whose
    reveal watches the .search-box around the input); everywhere else it opens the
    nav search box
  - the flyouts: one per category (image, pdf, utility), listing that section's
    cards on /tools in page order (sorted by name there, see check_nav.py). A tool
    reaches every menu by being added to /tools, then running --write.
  - the 404 page (one English file; its own script translates the page, nav included,
    on /es/ URLs): its language switch goes to /es/, and besides its English flyouts it
    carries the Spanish ones in a <template id="menuFlyouts-es"> (inert, so never
    reachable), which that script swaps in for the English ones on /es/ URLs

The copies leave out the sources' comments (the CSS's /* */ comments and the script's
whole-line // comments), which keeps every page about 5 KB lighter; the sources keep
them. A script comment after code on the same line is refused, since it would be copied.

--add adopts a page whose nav is the standard hand-copied one (the "Minimal nav
(Initiative 2)" CSS block, the header plus its height script, and the "Minimal nav
(Initiative 2)" script), for instance a page that arrives from main: it refuses unless
each piece is exactly the known copy (the header must equal this script's own output
for that page without flyouts, older wordings in OLD_STRINGS aside), so an adoption
never changes anything but the nav. The homepages and /tools were adopted by hand,
since their old nav built the flyouts at runtime.

check_nav_sync.py (CI: check-nav-sync) runs the --check comparison; --root DIR works
on a copy of the site.
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CSS_SOURCE = "assets/nav/site-nav.css"
JS_SOURCE = "assets/nav/site-nav.js"
TEMPLATE = "assets/nav/site-nav.html"
STRINGS = "assets/nav/strings.json"
CATALOG = {"en": "tools/index.html", "es": "es/tools/index.html"}
CATS = ("image", "pdf", "utility")
NOT_PAGES = {".git", ".github", ".claude", "assets", "docs", "scripts", "audit", "node_modules", "prototypes", "claude"}

CSS_START = "/* site-nav.css: start. Generated by scripts/sync_nav.py from assets/nav/site-nav.css; edit that file, not this region. */"
CSS_END = "/* site-nav.css: end */"
HTML_START = ("<!-- site-nav: start. Generated by scripts/sync_nav.py from assets/nav/site-nav.html, assets/nav/strings.json "
              "and the /tools cards; edit those, not this region. -->")
HTML_END = "<!-- site-nav: end -->"
JS_START = "<!-- site-nav.js: start. Generated by scripts/sync_nav.py from assets/nav/site-nav.js; edit that file, not this region. -->"
JS_END = "<!-- site-nav.js: end -->"
REGIONS = (("css", CSS_START, CSS_END), ("html", HTML_START, HTML_END), ("js", JS_START, JS_END))

# Pages whose menu differs from the default: the current item and the search icon.
PAGE_SETTINGS = {
    "index.html": {"search_target": "homeSearch", "search_watch": ".search-box"},
    "tools/index.html": {"search_target": "toolSearch", "current": "tools"},
    "blog/index.html": {"current": "blog"},
    # One English file for both languages (its script translates the page, nav included, on /es/ URLs), so its
    # language switch goes to the Spanish homepage, and it carries the Spanish flyouts too, in a <template> its
    # script swaps in on /es/ URLs (owner decision, 2026-11-11: the same flyouts as every other page).
    "404.html": {"other_url": "/es/", "translated_flyouts": "es"},
}
# Pages --add won't adopt (their old nav was special); they were migrated by hand.
NOT_ADOPTABLE = {"index.html", "tools/index.html"}
# Older wordings of a string that --add accepts in a page's old header and replaces with the current one
# (strings.json). The theme button's Spanish label was settled on 2026-11-11.
OLD_STRINGS = {"es": {"theme": ["Cambiar tema claro/oscuro"]}}

# The standard hand-copied pieces --add replaces (LF line endings), by sha256.
ADOPT_CSS_SHA256 = "9ca7e1a03690bd5ddf3773b99a09e7c51d0e4e9da8928d4b19efe1d1a815b6f5"
ADOPT_JS_SHA256 = "9170bdae9da592e762ac7c91730890f557380382d013f4266518aa29b3a17f19"

STYLE_OPEN = re.compile(r"<style\b[^>]*>", re.I)
STYLE_CLOSE = re.compile(r"</style\s*>", re.I)
SCRIPT_OPEN = re.compile(r"<script\b[^>]*>", re.I)
SCRIPT_CLOSE = re.compile(r"</script\s*>", re.I)
SECTION = re.compile(r"^<!-- @([a-z-]+) -->\n", re.M)
PLACEHOLDER = re.compile(r"\{\{([a-z_]+)\}\}")
CARD = re.compile(r'<a class="card tool-card" href="([^"]+)">.*?<div class="name tool-card-title">(.*?)</div>', re.S)
HEIGHT_SCRIPT = re.compile(r"<script>\(function\(\)\{var n=document\.querySelector\('\.site-nav'\);[^\n]*?</script>")
OLD_CSS_BANNER = "Minimal nav (Initiative 2): logo left"
OLD_JS = re.compile(r"<script>\n// Minimal nav \(Initiative 2\): the Menu panel and the Search icon\..*?</script>", re.S)


def read(path):
    with open(path, encoding="utf-8", newline="") as fh:
        return fh.read()


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)


def lf(text):
    return text.replace("\r\n", "\n")


def sha(text):
    return hashlib.sha256(lf(text).encode("utf-8")).hexdigest()


def strip_css(text):
    """The CSS as copied into pages: the source without its comments (they stay in the source file)."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return "".join(line.rstrip() + "\n" for line in text.split("\n") if line.strip())


def strip_js(text):
    """The script as copied into pages: the source without its whole-line // comments."""
    return "".join(line.rstrip() + "\n" for line in text.split("\n") if line.strip() and not line.strip().startswith("//"))


def newline_of(text):
    return "\r\n" if "\r\n" in text else "\n"


def pages(root):
    for f in sorted(root.rglob("*.html")):
        rel = f.relative_to(root)
        if rel.parts[0] not in NOT_PAGES:
            yield rel.as_posix()


def lang_of(rel):
    return "es" if rel.startswith("es/") else "en"


def page_key(rel):
    """The page's path within its language: es/tools/index.html -> tools/index.html."""
    return rel[3:] if rel.startswith("es/") else rel


def url_of(key, lang):
    path = "" if key == "index.html" else key[: -len("index.html")]
    return ("/es/" if lang == "es" else "/") + path


class Source:
    """Everything the regions are made from, read once."""

    def __init__(self, root):
        self.problems = []
        self.css = lf(read(root / CSS_SOURCE)).rstrip("\n") + "\n"
        self.js = lf(read(root / JS_SOURCE)).rstrip("\n") + "\n"
        if STYLE_CLOSE.search(self.css):
            self.problems.append(f"{CSS_SOURCE} contains a </style> tag, which would end the <style> element of every page it's copied into")
        if SCRIPT_CLOSE.search(self.js) or "<!--" in self.js:
            self.problems.append(f"{JS_SOURCE} contains </script> or <!--, which would break the <script> element it's copied into")
        for src, text in ((CSS_SOURCE, self.css), (JS_SOURCE, self.js)):
            if any(m in text for _, a, b in REGIONS for m in (a, b)):
                self.problems.append(f"{src} contains a region marker itself")
        if re.search(r"[^\s]\s*//|/\*", strip_js(self.js)):
            self.problems.append(f"{JS_SOURCE} has a comment after code or a /* */ comment; only whole-line // comments "
                                 "are stripped from the copies, so put comments on their own line")
        # Pages get the sources without their comments (smaller pages); the source files keep them.
        self.css, self.js = strip_css(self.css), strip_js(self.js)
        template = lf(read(root / TEMPLATE))
        parts = SECTION.split(template)
        self.sections = {parts[i]: parts[i + 1].rstrip("\n") for i in range(1, len(parts) - 1, 2)}
        for name in ("header", "search-form", "search-target", "flyout", "flyout-item", "flyouts-translated", "lang-en", "lang-es"):
            if name not in self.sections:
                self.problems.append(f"{TEMPLATE} has no @{name} section")
        self.strings = json.loads(read(root / STRINGS))
        if set(self.strings) != {"en", "es"} or set(self.strings["en"]) != set(self.strings["es"]):
            self.problems.append(f"{STRINGS} must hold the same keys for en and es")
        self.catalog = {}
        for lang, rel in CATALOG.items():
            text = read(root / rel)
            self.catalog[lang] = {}
            for cat in CATS:
                sec = re.search(rf'<section class="category-section" id="{cat}"[^>]*>(.*?)</section>', text, re.S)
                cards = CARD.findall(sec.group(1)) if sec else []
                if not cards:
                    self.problems.append(f"{rel}: no tool cards found in the {cat} section, so the {cat} flyout would be empty")
                self.catalog[lang][cat] = cards

    def fill(self, name, values):
        def sub(m):
            if m.group(1) not in values:
                raise KeyError(f"{TEMPLATE} @{name}: no value for {{{{{m.group(1)}}}}}")
            return values[m.group(1)]
        return PLACEHOLDER.sub(sub, self.sections[name])

    def header(self, rel, flyouts=True):
        """The generated header region content (LF) for a page (flyouts=False: the hand-copied header --add expects)."""
        lang, key = lang_of(rel), page_key(rel)
        t = dict(self.strings[lang])
        settings = PAGE_SETTINGS.get(key, {})
        tools_url = url_of("tools/index.html", lang)
        values = {**t, "home_url": url_of("index.html", lang), "support_url": url_of("support/index.html", lang),
                  "tools_url": tools_url, "blog_url": url_of("blog/index.html", lang),
                  "current_tools": ' aria-current="page"' if settings.get("current") == "tools" else "",
                  "current_blog": ' aria-current="page"' if settings.get("current") == "blog" else "",
                  "search_target": settings.get("search_target", ""),
                  "search_watch": f' data-search-watch="{settings["search_watch"]}"' if settings.get("search_watch") else ""}
        values["search"] = self.fill("search-target" if settings.get("search_target") else "search-form", values)
        values["search"] = values["search"].replace("{{search}}", t["search"])
        other_url = settings.get("other_url") or url_of(key, "en" if lang == "es" else "es")
        values["lang_switch"] = self.fill("lang-" + lang, {"other_url": other_url})
        for cat in CATS:
            values["flyout_" + cat] = self.flyout(lang, cat)
        # the search snippets use {{search}} as a string too: fill the header once the snippet is in
        out = self.fill("header", {**values, "search": "\x00SEARCH\x00"}).replace("\x00SEARCH\x00", values["search"])
        if not flyouts:
            out = "\n".join(line for line in out.split("\n") if 'class="menu-flyout"' not in line)
            out = re.sub(r' data-flyout="menuFlyout-\w+"', "", out)
        elif settings.get("translated_flyouts"):
            # The other language's flyouts, inert in a <template> before </header> (the 404 page's script swaps them in).
            other = settings["translated_flyouts"]
            panels = "\n".join(self.flyout(other, cat) for cat in CATS)
            template = self.fill("flyouts-translated", {"lang": other, "flyouts": panels})
            end = "\n  </nav>\n</header>\n"
            assert out.count(end) == 1, "the header template no longer ends with </nav></header>"
            out = out.replace(end, "\n  </nav>\n" + template + "\n</header>\n")
        return out + "\n"

    def flyout(self, lang, cat):
        """One category's flyout panel, listing the /tools cards of that language."""
        items = "".join(self.fill("flyout-item", {"href": h, "name": n.strip()}) for h, n in self.catalog[lang][cat])
        return self.fill("flyout", {"cat": cat, "label": self.strings[lang]["cat_" + cat], "items": items})

    def region(self, kind, rel):
        if kind == "css":
            return self.css
        if kind == "js":
            return "<script>\n" + self.js + "</script>\n"
        return self.header(rel)


def fill_values_check(source):
    """Fail early on a template placeholder with no value (a typo in the template or strings)."""
    try:
        source.header("index.html")
        source.header("es/whatsapp-link-generator/index.html")
    except KeyError as e:
        source.problems.append(str(e.args[0]))


def find_regions(text):
    """{kind: (content_start, content_end)} and a list of problems. Empty dict when the page has no markers."""
    found, problems = {}, []
    for kind, start, end in REGIONS:
        a, b = text.count(start), text.count(end)
        if not a and not b:
            continue
        if a != 1 or b != 1:
            problems.append(f"has {a} site-nav {kind} start marker(s) and {b} end marker(s); it needs exactly one of each")
            continue
        s, e = text.index(start), text.index(end)
        if e < s:
            problems.append(f"has its site-nav {kind} end marker before its start marker")
            continue
        content = s + len(start)
        if text.startswith("\r\n", content):
            content += 2
        elif text.startswith("\n", content):
            content += 1
        found[kind] = (content, e)
    if found and set(found) != {"css", "html", "js"} and not problems:
        problems.append(f"has only the {', '.join(sorted(found))} site-nav region(s); a page with the generated menu needs all three (css, html, js)")
    if "css" in found:
        s = found["css"][0]
        opens = [m for m in STYLE_OPEN.finditer(text) if m.end() <= s]
        close = STYLE_CLOSE.search(text, opens[-1].end()) if opens else None
        if not opens or not close or close.start() < found["css"][1]:
            problems.append("has its site-nav.css region outside a single <style> element")
    for kind in ("html", "js"):
        if kind in found:
            s = found[kind][0]
            last_style = [m for m in STYLE_OPEN.finditer(text) if m.end() <= s]
            last_script = [m for m in SCRIPT_OPEN.finditer(text) if m.end() <= s]
            for opener, closer, tag in ((last_style, STYLE_CLOSE, "<style>"), (last_script, SCRIPT_CLOSE, "<script>")):
                if opener:
                    c = closer.search(text, opener[-1].end())
                    if c and c.start() >= s:
                        problems.append(f"has its site-nav {kind} region inside a {tag} element")
    if "html" in found and "js" in found and found["js"][0] < found["html"][0]:
        problems.append("has its site-nav.js region before its header region (the script needs the menu above it)")
    return (found if not problems else {}), problems


def sync_text(text, rel, source):
    """(new text or None when in sync, problems, carries regions)."""
    found, problems = find_regions(text)
    if problems:
        return None, problems, True
    if not found:
        return None, [], False
    if rel.startswith("es/") and page_key(rel) == "404.html":
        return None, ["the 404 page is one English file at the site root (it translates itself on /es/ URLs); there is no es/404.html"], True
    target = PAGE_SETTINGS.get(page_key(rel), {}).get("search_target")
    if target and f'id="{target}"' not in text:
        problems.append(f"its search icon targets #{target}, which isn't on the page")
    nl = newline_of(text)
    out, changed = text, False
    for kind, (s, e) in sorted(found.items(), key=lambda kv: -kv[1][0]):  # from the end, so offsets stay valid
        want = source.region(kind, rel)
        if lf(out[s:e]) != want:
            out = out[:s] + want.replace("\n", nl) + out[e:]
            changed = True
    return (out if changed else None), problems, True


def adopt(text, rel, source):
    """Turn a standard hand-copied nav into empty regions (synced afterwards). (new text or None, problem or None)."""
    key = page_key(rel)
    if key in NOT_ADOPTABLE:
        return None, "is a special page (its old nav built the flyouts at runtime, or translates itself); migrate it by hand"
    nl = newline_of(text)
    t = lf(text)
    # 1. the CSS block: from the banner before "Minimal nav (Initiative 2)" to the next block or </style>
    i = t.find(OLD_CSS_BANNER)
    if i < 0 or t.count(OLD_CSS_BANNER) != 1:
        return None, "has no single \"Minimal nav (Initiative 2)\" CSS block"
    a = t.rfind("/* ====", 0, i)
    ends = [x for x in (t.find("/* Breadcrumbs (Initiative 2)", a), t.find("</style>", a)) if x > 0]
    b = min(ends)
    if sha(t[a:b]) != ADOPT_CSS_SHA256:
        return None, "has a \"Minimal nav (Initiative 2)\" CSS block that isn't the standard copy"
    # 2. the header plus its height script
    hm = re.search(r'<header class="site-nav">.*?</header>\n', t, re.S)
    if not hm:
        return None, "has no <header class=\"site-nav\">"
    header = hm.group(0)
    sm = HEIGHT_SCRIPT.match(t, hm.end())
    if not sm:
        return None, "has no --site-nav-h script right after its header"
    old_header = header + sm.group(0) + "\n"
    for key_name, olds in OLD_STRINGS.get(lang_of(rel), {}).items():
        for old in olds:
            old_header = old_header.replace(f'"{old}"', f'"{source.strings[lang_of(rel)][key_name]}"')
    if old_header != source.header(rel, flyouts=False):
        return None, "has a header that differs from the generated one (without flyouts); fix it or migrate it by hand"
    # 3. the nav script
    jm = list(OLD_JS.finditer(t))
    if len(jm) != 1 or sha(jm[0].group(0)) != ADOPT_JS_SHA256:
        return None, "has no single standard \"Minimal nav (Initiative 2)\" script"
    end_of_js = jm[0].end() + (1 if t.startswith("\n", jm[0].end()) else 0)
    pieces = [(a, b, CSS_START + "\n" + CSS_END + "\n"),
              (hm.start(), sm.end() + 1, HTML_START + "\n" + HTML_END + "\n"),
              (jm[0].start(), end_of_js, JS_START + "\n" + JS_END + "\n")]
    for s, e, repl in sorted(pieces, reverse=True):
        t = t[:s] + repl + t[e:]
    return t.replace("\n", nl), None


def run(root, write_changes=False, check=False, add=()):
    """Returns (exit code, report lines)."""
    lines = []
    source = Source(root)
    fill_values_check(source)
    problems = list(source.problems)
    if problems:
        return 1, [f"  - {p}" for p in problems]
    texts = {}
    for rel in add:
        new, problem = adopt(read(root / rel), rel, source)
        if problem:
            problems.append(f"{rel}: {problem}")
            continue
        texts[rel] = new
        lines.append(f"  {'adopted' if write_changes else 'would adopt'}: {rel}")
    adopting, changed = 0, []
    for rel in pages(root):
        text = texts.get(rel) or read(root / rel)
        new, page_problems, carries = sync_text(text, rel, source)
        problems += [f"{rel}: {p}" for p in page_problems]
        if page_problems or not carries:
            continue
        adopting += 1
        if new is not None or rel in texts:
            changed.append(rel)
            if write_changes:
                write(root / rel, new if new is not None else text)
    for rel in changed:
        lines.append(f"  {'synced' if write_changes else 'out of date'}: {rel}")
    for p in problems:
        lines.append(f"  - {p}")
    lines.append(f"{adopting} page(s) carry the generated site menu: {adopting - len(changed)} in sync, "
                 f"{len(changed)} {'rewritten' if write_changes else 'out of date'}; {len(problems)} problem(s)")
    if problems:
        return 1, lines
    if check and changed:
        lines.append("Run: python scripts/sync_nav.py --write")
        return 1, lines
    if not write_changes and not check:
        lines.append("Dry run: nothing written." + (" Run again with --write to apply." if changed else ""))
    return 0, lines


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="rewrite out-of-date regions (and adopt the --add pages)")
    mode.add_argument("--check", action="store_true", help="exit 1 if any region differs from the source or is broken")
    ap.add_argument("--add", nargs="+", default=(), metavar="PAGE", help="adopt these pages (with --write, or as a dry run)")
    ap.add_argument("--root", default=str(REPO_ROOT), help="site root (default: this repo)")
    args = ap.parse_args()
    if args.check and args.add:
        ap.error("--add can't be combined with --check")
    sys.stdout.reconfigure(encoding="utf-8")
    code, lines = run(Path(args.root), write_changes=args.write, check=args.check, add=tuple(args.add))
    print("\n".join(lines))
    return code


if __name__ == "__main__":
    sys.exit(main())
